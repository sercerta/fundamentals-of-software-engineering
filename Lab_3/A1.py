# A1. Определить, лежат ли две точки в одной координатной четверти.
# По условию все координаты не равны нулю.

# Ввод координат двух точек
x1 = int(input())
y1 = int(input())
x2 = int(input())
y2 = int(input())

# Проверяем, находятся ли обе точки в первой четверти
if x1 > 0 and y1 > 0 and x2 > 0 and y2 > 0:
    print("Yes, I")
# Проверяем вторую четверть
elif x1 < 0 and y1 > 0 and x2 < 0 and y2 > 0:
    print("Yes, II")
# Проверяем третью четверть
elif x1 < 0 and y1 < 0 and x2 < 0 and y2 < 0:
    print("Yes, III")
# Проверяем четвертую четверть
elif x1 > 0 and y1 < 0 and x2 > 0 and y2 < 0:
    print("Yes, IV")
# Если ни одно условие не выполнилось, точки в разных четвертях
else:
    print("No")
